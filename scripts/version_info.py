"""Generate Windows PE VSVersionInfo metadata for PyInstaller builds.

Reads the canonical semantic version from ``pyproject.toml`` and emits a
UTF-8 PyInstaller version resource file describing ``数据查重程序``.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path
from typing import Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_PATH = PROJECT_ROOT / "build_version_info.txt"

APP_PRODUCT_NAME = "数据查重程序"
APP_INTERNAL_NAME = "data-dedup-tool"
APP_ORIGINAL_FILENAME = "data-dedup-tool.exe"
APP_COMPANY_NAME = "DataDedupTool"
APP_FILE_DESCRIPTION = "数据查重程序 - 桌面端数据查重与多表处理工具"
APP_LEGAL_COPYRIGHT = "Copyright (c) yellowdking. MIT License."


def read_project_version(project_root: Optional[Path] = None) -> str:
    """Read ``[project].version`` from ``pyproject.toml``."""
    root = Path(project_root) if project_root is not None else PROJECT_ROOT
    pyproject = root / "pyproject.toml"
    if not pyproject.is_file():
        return "1.2.0"

    raw = pyproject.read_text(encoding="utf-8")
    try:
        data = tomllib.loads(raw)
        version = str(data.get("project", {}).get("version", "")).strip()
        if version:
            return version
    except Exception:
        pass

    match = re.search(r'(?m)^\s*version\s*=\s*"([^"]+)"', raw)
    return match.group(1).strip() if match else "1.2.0"


def parse_version_tuple(version_str: str) -> tuple[int, int, int, int]:
    """Convert a semantic version string such as ``1.2.0`` into a 4-int Windows tuple."""
    nums = [int(part) for part in re.findall(r"\d+", version_str)]
    while len(nums) < 4:
        nums.append(0)
    return (nums[0], nums[1], nums[2], nums[3])


def render_version_info_text(
    version_str: Optional[str] = None,
    project_root: Optional[Path] = None,
) -> str:
    """Render a UTF-8 PyInstaller ``VSVersionInfo`` definition string."""
    ver = (version_str or read_project_version(project_root)).strip()
    ver_tuple = parse_version_tuple(ver)
    ver_dotted = ".".join(str(x) for x in ver_tuple)

    return f"""# UTF-8
# Auto-generated by scripts/version_info.py — do not commit manually.
VSVersionInfo(
    ffi=FixedFileInfo(
        filevers={ver_tuple!r},
        prodvers={ver_tuple!r},
        mask=0x3F,
        flags=0x0,
        OS=0x40004,
        fileType=0x1,
        subtype=0x0,
        date=(0, 0),
    ),
    kids=[
        StringFileInfo(
            [
                StringTable(
                    "080404B0",
                    [
                        StringStruct("CompanyName", {APP_COMPANY_NAME!r}),
                        StringStruct("FileDescription", {APP_FILE_DESCRIPTION!r}),
                        StringStruct("FileVersion", {ver_dotted!r}),
                        StringStruct("InternalName", {APP_INTERNAL_NAME!r}),
                        StringStruct("LegalCopyright", {APP_LEGAL_COPYRIGHT!r}),
                        StringStruct("OriginalFilename", {APP_ORIGINAL_FILENAME!r}),
                        StringStruct("ProductName", {APP_PRODUCT_NAME!r}),
                        StringStruct("ProductVersion", {ver!r}),
                    ],
                )
            ]
        ),
        VarFileInfo([VarStruct("Translation", [0x0804, 1200])]),
    ],
)
"""


def write_version_info_file(
    output_path: Optional[Path] = None,
    version_str: Optional[str] = None,
    project_root: Optional[Path] = None,
) -> Path:
    """Write the generated ``VSVersionInfo`` file in UTF-8 and return its path."""
    target = Path(output_path) if output_path is not None else DEFAULT_OUTPUT_PATH
    content = render_version_info_text(version_str=version_str, project_root=project_root)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8", newline="\n")
    return target


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate PyInstaller VSVersionInfo file.")
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Output path for the generated version info text file.",
    )
    parser.add_argument(
        "--version",
        type=str,
        default="",
        help="Override version string (defaults to pyproject.toml [project].version).",
    )
    args = parser.parse_args(argv)
    ver = args.version.strip() or read_project_version()
    out_path = write_version_info_file(output_path=args.output, version_str=ver)
    print(f"Generated Windows version info ({ver}): {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
